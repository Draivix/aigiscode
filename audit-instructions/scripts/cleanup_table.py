#!/usr/bin/env python3
"""Cleanup ledger and the table of code to get rid of.

  python3 cleanup_table.py init <Module>                       # put every open finding of a module on the ledger as todo
  python3 cleanup_table.py set <F-id>[,<F-id>…] <state> [--mr N] [--note TEXT] [--module M] [--loc N]
  python3 cleanup_table.py render                              # write out/CLEANUP.md

States: todo · in_progress · in_mr · merged (code gone or unified, MR merged) · waiting_tombstone
(dead symbol, deleted after the observation window) · kept (reviewed, no change: reason in note) ·
needs_owner (a decision only the owner can make: question in note).
The ledger (out/cleanup/ledger.jsonl) is append-only; the last line per finding wins.
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter, defaultdict
from datetime import datetime, timezone
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "out"
MERGED = OUT / "registry.merged.jsonl"
LEDGER = OUT / "cleanup" / "ledger.jsonl"
TABLE = OUT / "CLEANUP.md"
STATES = ("todo", "in_progress", "in_mr", "merged", "waiting_tombstone", "kept", "needs_owner")
KIND_ORDER = ("dead_branch", "unused_param", "clone_exact", "clone_semantic", "variant_mergeable", "redundant_layer",
              "repeated_validation", "double_path", "suspicious", "dead_symbol")
MR_URL = "https://gitlab.apertia.cz/draivix/draivix/-/merge_requests/"


def now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def registry() -> dict[str, dict]:
    return {r["id"]: r for r in (json.loads(l) for l in open(MERGED) if l.strip())}


def ledger() -> dict[str, dict]:
    state: dict[str, dict] = {}
    if LEDGER.exists():
        for line in open(LEDGER):
            if line.strip():
                e = json.loads(line)
                state[e["finding_id"]] = {**state.get(e["finding_id"], {}), **e}
    return state


def append(entry: dict) -> None:
    LEDGER.parent.mkdir(parents=True, exist_ok=True)
    with open(LEDGER, "a") as f:
        f.write(json.dumps({"ts": now(), **entry}, ensure_ascii=False) + "\n")


def module_findings(reg: dict[str, dict], module: str) -> list[dict]:
    pre_file, pre_sym = f"app/Modules/{module}/", f"App\\Modules\\{module}\\"
    out = []
    for r in reg.values():
        if r["status"] == "rejected":
            continue
        files = {e.get("file", "") for e in r.get("evidence") or [] if isinstance(e, dict)}
        if any(f.startswith(pre_file) for f in files) or any(s.startswith(pre_sym) for s in r.get("symbols") or []):
            out.append(r)
    return out


def cmd_init(module: str) -> None:
    reg, led = registry(), ledger()
    n = 0
    for r in module_findings(reg, module):
        if r["id"] in led:
            continue
        state = "waiting_tombstone" if r["kind"] == "dead_symbol" else "todo"
        append({"finding_id": r["id"], "module": module, "state": state})
        n += 1
    print(f"{module}: {n} findings put on the ledger")


def cmd_set(ids: str, state: str, mr: str | None, note: str | None, module: str | None, loc: int | None) -> None:
    if state not in STATES:
        sys.exit(f"state must be one of {STATES}")
    led = ledger()
    for fid in ids.split(","):
        e = {"finding_id": fid, "state": state}
        if module or fid not in led:
            e["module"] = module or "?"
        if mr:
            e["mr"] = mr
        if note:
            e["note"] = note
        if loc is not None:
            e["loc_removed"] = loc
        append(e)
    print(f"{len(ids.split(','))} finding(s) → {state}")


def short_symbols(r: dict, module: str) -> str:
    syms = [s.replace("App\\Modules\\", "").replace(f"{module}\\", "") for s in r.get("symbols") or []]
    head = ", ".join(f"`{s.split(chr(92))[-1]}`" for s in syms[:3])
    return head + (f" +{len(syms) - 3}" if len(syms) > 3 else "")


def cmd_render() -> None:
    reg, led = registry(), ledger()
    by_module: dict[str, list[tuple[dict, dict]]] = defaultdict(list)
    for fid, e in led.items():
        r = reg.get(fid)
        if r is not None:
            by_module[e.get("module", "?")].append((r, e))
    lines = ["# Cleanup – the table of code to get rid of", "",
             "Generated by `audit-instructions/scripts/cleanup_table.py render` from the audit registry and the cleanup "
             "ledger (`cleanup/ledger.jsonl`). One row per audit finding; module by module, smallest first. "
             "States: **todo**, **in_mr**, **merged** (code removed or unified, MR merged), **waiting_tombstone** "
             "(dead symbol: deleted after the 30-day observation window, `TOMBSTONES.md`), **kept** (reviewed, "
             "the finding does not hold on current code, reason given), **needs_owner** (a decision for David).", ""]
    total = Counter()
    summary = ["| Module | Findings | merged | in_mr | todo | waiting_tombstone | kept | needs_owner | LOC removed |",
               "|---|---|---|---|---|---|---|---|---|"]
    for module in sorted(by_module, key=lambda m: len(by_module[m])):
        rows = by_module[module]
        c = Counter(e["state"] for _, e in rows)
        loc = sum(int(e.get("loc_removed") or 0) for _, e in rows)
        total.update(c)
        total["loc"] += loc
        summary.append(f"| {module} | {len(rows)} | {c['merged']} | {c['in_mr']} | {c['todo'] + c['in_progress']} | "
                       f"{c['waiting_tombstone']} | {c['kept']} | {c['needs_owner']} | {loc} |")
    lines += summary + [""]
    for module in sorted(by_module, key=lambda m: len(by_module[m])):
        rows = sorted(by_module[module], key=lambda re_: (STATES.index(re_[1]["state"]) if re_[1]["state"] in STATES else 9,
                                                          KIND_ORDER.index(re_[0]["kind"]) if re_[0]["kind"] in KIND_ORDER else 99))
        lines += [f"## {module}", "", "| Finding | Kind | Audit | What | Symbols | State | MR | Note |", "|---|---|---|---|---|---|---|---|"]
        for r, e in rows:
            mr = e.get("mr")
            mr_cell = f"[!{mr}]({MR_URL}{mr})" if mr and str(mr).isdigit() else (mr or "")
            title = (r.get("title") or "").replace("|", "\\|")[:110]
            note = (e.get("note") or "").replace("|", "\\|")[:220]
            lines.append(f"| {r['id']} | {r['kind']} | {r['status']} | {title} | {short_symbols(r, module)} | "
                         f"**{e['state']}** | {mr_cell} | {note} |")
        lines.append("")
    TABLE.write_text("\n".join(lines) + "\n")
    print(f"{TABLE} written: {sum(len(v) for v in by_module.values())} findings, states {dict(total)}")


def main() -> None:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("init"); p.add_argument("module")
    p = sub.add_parser("set"); p.add_argument("ids"); p.add_argument("state")
    p.add_argument("--mr"); p.add_argument("--note"); p.add_argument("--module"); p.add_argument("--loc", type=int)
    sub.add_parser("render")
    a = ap.parse_args()
    if a.cmd == "init":
        cmd_init(a.module)
    elif a.cmd == "set":
        cmd_set(a.ids, a.state, a.mr, a.note, a.module, a.loc)
    else:
        cmd_render()


if __name__ == "__main__":
    main()
